#!/usr/bin/env python3
"""Rust dependency license inventory for engine/Cargo.lock.

Reads `cargo metadata --locked --all-features` (every optional feature, every
target platform) and writes licenses/rust-crates.tsv: one row per third-party
crate in the resolved graph, including build and dev dependencies.

  tool/rust_license_inventory.py           # regenerate the inventory
  tool/rust_license_inventory.py --check   # fail if stale or a license is not allowlisted

The allowlist is deliberately narrow. A new license expression fails the check
until someone has read it and added it here.
"""

from __future__ import annotations

import argparse
import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MANIFEST = ROOT / "engine" / "Cargo.toml"
INVENTORY = ROOT / "licenses" / "rust-crates.tsv"

# Every expression below offers at least one permissive option (MIT, Apache-2.0,
# BSD, Zlib, ISC, CC0, Unicode) except where noted.
ALLOWED = {
    "MIT",
    "Apache-2.0",
    "Zlib",
    "ISC",
    "CC0-1.0",
    "MIT OR Apache-2.0",
    "Apache-2.0 OR MIT",
    "MIT/Apache-2.0",
    "Apache-2.0/MIT",
    "Apache-2.0 WITH LLVM-exception OR Apache-2.0 OR MIT",
    "Zlib OR Apache-2.0 OR MIT",
    "MIT OR Apache-2.0 OR Zlib",
    "MIT OR Zlib OR Apache-2.0",
    "Unlicense OR MIT",
    "Unlicense/MIT",
    "BSD-2-Clause OR Apache-2.0 OR MIT",
    "0BSD OR MIT OR Apache-2.0",
    "(MIT OR Apache-2.0) AND Unicode-3.0",
    # r-efi: used under MIT OR Apache-2.0; the LGPL option is not taken.
    "MIT OR Apache-2.0 OR LGPL-2.1-or-later",
}

# Build-time tools whose code is not linked into any runtime artifact.
BUILD_ONLY_EXCEPTIONS = {
    # cbindgen generates kineto_engine.h at build time. MPL-2.0 covers
    # cbindgen's own source; its generated output is not a Covered Work.
    ("cbindgen", "MPL-2.0"),
}

HEADER = "# Generated by tool/rust_license_inventory.py from engine/Cargo.lock. Do not edit.\n"
COLUMNS = "name\tversion\tlicense\trepository\n"


def metadata() -> dict:
    out = subprocess.run(
        [
            "cargo",
            "metadata",
            "--locked",
            "--all-features",
            "--format-version",
            "1",
            "--manifest-path",
            str(MANIFEST),
        ],
        check=True,
        capture_output=True,
        text=True,
    ).stdout
    return json.loads(out)


def rows(meta: dict) -> list[tuple[str, str, str, str]]:
    resolved = {node["id"] for node in meta["resolve"]["nodes"]}
    result = []
    for package in meta["packages"]:
        if package["id"] not in resolved or package["source"] is None:
            continue  # workspace crates are owner-authored (MIT, LICENSE)
        license_expr = package.get("license") or f"SEE-FILE:{package.get('license_file')}"
        result.append(
            (
                package["name"],
                package["version"],
                license_expr,
                package.get("repository") or "",
            )
        )
    return sorted(result)


def render(table: list[tuple[str, str, str, str]]) -> str:
    return HEADER + COLUMNS + "".join("\t".join(row) + "\n" for row in table)


def disallowed(table: list[tuple[str, str, str, str]]) -> list[str]:
    bad = []
    for name, version, license_expr, _ in table:
        if license_expr in ALLOWED or (name, license_expr) in BUILD_ONLY_EXCEPTIONS:
            continue
        bad.append(f"{name} {version}: {license_expr}")
    return bad


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()

    table = rows(metadata())
    text = render(table)
    bad = disallowed(table)

    if args.check:
        ok = True
        if not INVENTORY.is_file() or INVENTORY.read_text() != text:
            print(f"FAIL: {INVENTORY.relative_to(ROOT)} is stale; run {Path(__file__).relative_to(ROOT)}")
            ok = False
        if bad:
            print("FAIL: license expressions not on the allowlist:")
            print("\n".join(f"  {line}" for line in bad))
            ok = False
        if ok:
            print(f"OK: {len(table)} third-party crates, all licenses allowlisted, inventory current")
        return 0 if ok else 1

    INVENTORY.parent.mkdir(parents=True, exist_ok=True)
    INVENTORY.write_text(text)
    print(f"wrote {INVENTORY.relative_to(ROOT)} ({len(table)} crates)")
    if bad:
        print("WARNING: not allowlisted:\n" + "\n".join(f"  {line}" for line in bad))
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
